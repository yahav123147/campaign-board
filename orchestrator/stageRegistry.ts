export function getSubTaskDef(
  stageNumber: StageNumber,
  subTaskId: string,
  assetType: AssetType = "sales-page",
  pipeline: Pipeline = "council",
): SubTaskDef {
  const stage = getStageDef(stageNumber, assetType, pipeline);
  const sub = stage.subTasks.find(s => s.id === subTaskId);
  if (!sub) throw new Error(`SubTask ${subTaskId} not in stage ${stageNumber}`);
  return sub;
}

