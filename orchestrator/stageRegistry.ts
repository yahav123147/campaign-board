/**
 * The stage list for an asset type. Only stage 4 differs for every other
 * type, so the rest of the registry stays a single definition and cannot
 * drift between them. Upsell is the one exception on top of that: nobody can
 * reach it from an ad, since it only exists inside a checkout session, so a
 * run of this type ends after stage 5 builds the page. Stages 6 to 9 (ad
 * angles, ad copy and creatives, pixel verification, campaign plan) never get
 * created for it. This trims the returned list only, so a stage not in it is
 * never built by `decide` and never gets a card; `StageNumber` itself stays 1
 * to 9 for every other type.
 */
export function stageRegistryFor(assetType: AssetType = "sales-page", pipeline: Pipeline = "council"): StageDef[] {
  if (pipeline === "direct") return DIRECT_STAGE_REGISTRY;
  const stage4 = STAGE_4_BY_TYPE[assetType];
  const stages = stage4
    ? STAGE_REGISTRY.map((stage) => (stage.number === 4
        ? { ...stage, title: stage4.title, subTasks: stage4.subTasks }
        : stage))
    : STAGE_REGISTRY;
  return assetType === "upsell-page" ? stages.filter((stage) => stage.number <= 5) : stages;
}

export function getStageDef(n: StageNumber, assetType: AssetType = "sales-page", pipeline: Pipeline = "council"): StageDef {
  const def = stageRegistryFor(assetType, pipeline).find(s => s.number === n);
  if (!def) throw new Error(`Stage ${n} not in registry`);
  return def;
}

